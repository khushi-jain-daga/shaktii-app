function safe(value) { return String(value ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' '); }

function buildReport(data) {
  const fileName = data?.fileName || data?.metadata?.fileName || 'Uploaded Analysis';
  const meta = data?.metadata || {};
  const severity = data?.severityBreakdown || { critical: 0, high: 0, medium: 0, low: 0, info: 0 };
  const findings = Array.isArray(data?.findings) ? data.findings : [];
  const iocs = Array.isArray(data?.iocs) ? data.iocs : [];
  const remediation = Array.isArray(data?.remediationChecklist) ? data.remediationChecklist : [];
  const risk = Number(meta.overallRiskScore || data?.score || 0);
  const verdict = risk >= 80 ? 'High Revision Required' : risk >= 60 ? 'Needs Improvement' : risk >= 35 ? 'Good with Review' : 'Low Risk / Good';

  let md = `# SHAKTII PKAP ANALYSIS REPORT\n\n`;
  md += `**Analysed File:** ${fileName}\n`;
  md += `**Generated:** ${new Date().toLocaleString('en-IN')}\n`;
  md += `**Analysis Status:** Completed\n`;
  md += `**Overall Risk Score:** ${risk}/100\n`;
  md += `**Final Verdict:** ${verdict}\n\n---\n\n`;
  md += `## Executive Summary\n${data?.executiveSummary || 'PKAP analysis completed from uploaded content.'}\n\n`;
  md += `## KPI Summary\n| Metric | Value |\n| --- | ---: |\n`;
  md += `| Critical findings | ${severity.critical || 0} |\n| High findings | ${severity.high || 0} |\n| Medium findings | ${severity.medium || 0} |\n| Low findings | ${severity.low || 0} |\n| IOCs extracted | ${iocs.length} |\n| Total findings | ${findings.length} |\n\n`;
  md += `## Severity Analysis\n| Severity | Count | Interpretation |\n| --- | ---: | --- |\n`;
  md += `| Critical | ${severity.critical || 0} | Immediate attention required |\n| High | ${severity.high || 0} | Strong anomaly or risky behavior |\n| Medium | ${severity.medium || 0} | Review recommended |\n| Low | ${severity.low || 0} | Minor issue |\n| Info | ${severity.info || 0} | Informational event |\n\n`;
  md += `## Detailed Findings\n`;
  if (findings.length) {
    md += `| # | Severity | Type | Source | Description | Recommendation |\n| ---: | --- | --- | --- | --- | --- |\n`;
    findings.slice(0, 60).forEach((f, i) => {
      md += `| ${i + 1} | ${safe(f.severity || 'Info')} | ${safe(f.eventType || 'Event')} | ${safe(f.sourceIP || '-')} | ${safe(f.description || '-')} | ${safe(f.recommendation || f.mitreTag || 'Review evidence and validate impact.')} |\n`;
    });
  } else {
    md += `No actionable findings were detected.\n`;
  }
  md += `\n## Indicators of Compromise\n`;
  if (iocs.length) {
    md += `| Indicator | Type | Reputation |\n| --- | --- | --- |\n`;
    iocs.slice(0, 80).forEach((ioc) => { md += `| ${safe(ioc.value)} | ${safe(ioc.type)} | ${safe(ioc.reputation || 'Unknown')} |\n`; });
  } else md += `No IOCs were extracted.\n`;
  md += `\n## Recommendations\n`;
  (remediation.length ? remediation : ['Validate uploaded evidence.', 'Review high severity findings.', 'Re-run analysis after corrections or containment.']).forEach((r, i) => { md += `${i + 1}. ${r}\n`; });
  md += `\n## Final Verdict\n${verdict}. The verdict is based on the detected severity distribution, number of findings, IOC reputation and remediation requirements.\n\n---\nGenerated by SHAKTII / PKAP Analyzer.`;
  return md;
}

async function geminiReport(prompt) {
  if (!process.env.GEMINI_API_KEY) throw new Error('GEMINI_API_KEY missing');
  const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${encodeURIComponent(process.env.GEMINI_API_KEY)}`;
  const response = await fetch(endpoint, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ contents: [{ parts: [{ text: prompt }] }], generationConfig: { temperature: 0.1 } }) });
  if (!response.ok) throw new Error(`Gemini ${response.status}`);
  const payload = await response.json();
  return payload?.candidates?.[0]?.content?.parts?.[0]?.text?.trim();
}

export default async function handler(req, res) {
  if (req.method !== 'POST') return res.status(405).json({ success: false, error: 'Method not allowed' });
  const analysisData = req.body?.analysisData;
  if (!analysisData) return res.status(400).json({ success: false, error: 'analysisData is required' });
  const fallback = buildReport(analysisData);
  try {
    const prompt = `Generate a professional Markdown PKAP audit report using only this actual analysis data. Include Executive Summary, Overall Score, Severity Analysis, IOC Analysis, Detailed Findings, Recommendations and Final Verdict. Do not invent facts.\n\n${JSON.stringify(analysisData).slice(0, 30000)}`;
    const ai = await geminiReport(prompt);
    return res.status(200).json({ success: true, report: ai && ai.length > 200 ? ai : fallback, providerUsed: ai ? 'Gemini' : 'Local report builder' });
  } catch {
    return res.status(200).json({ success: true, report: fallback, providerUsed: 'Local report builder' });
  }
}
